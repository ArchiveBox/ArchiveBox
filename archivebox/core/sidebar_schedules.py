"""Bounded Scheduled Crawls sidebar entries, using the native run relation."""

from urllib.parse import urlsplit

from django.db.models import Exists, F, OuterRef, Q
from django.db.models.functions import Substr
from django.urls import reverse
from django.utils import timezone
from django.utils.dateparse import parse_datetime

from archivebox.crawls.models import Crawl, CrawlSchedule
from archivebox.crawls.schedule_util import SCHEDULE_ALIASES, normalize_schedule
from archivebox.uuid_compat import compact_uuid


FREQUENCIES = {SCHEDULE_ALIASES[alias]: alias.capitalize() for alias in ("minutely", "hourly", "daily", "weekly", "monthly", "yearly")}


def schedule_sidebar_allowed(request):
    user = request.user
    return (
        user.is_active
        and user.is_staff
        and (user.has_perm("crawls.view_crawlschedule") or user.has_perm("crawls.change_crawlschedule"))
        and (user.has_perm("crawls.view_crawl") or user.has_perm("crawls.change_crawl"))
    )


def schedule_add_actions(request):
    if not schedule_sidebar_allowed(request) or not request.user.has_perm("crawls.add_crawlschedule"):
        return []
    return [{"label": "New Scheduled Crawl", "url": reverse("admin:crawls_crawlschedule_add")}]


def _schedule_name(row):
    hostnames = {}
    # Reuse Crawl's plain-text/JSONL seed parsing for the rows already paged in.
    for _, url in Crawl.iter_url_lines(row["urls"]):
        if not url:
            continue
        try:
            hostname = urlsplit(url).hostname
        except ValueError:
            continue
        if hostname:
            hostnames[hostname] = None
    label = ",".join(hostnames) or f"Scheduled Crawl {str(row['pk'])[-8:]}"
    frequency = FREQUENCIES.get(normalize_schedule(row["schedule"]), row["schedule"])
    return f"{label} ({frequency.lower()})"


def _cursor_filter(cursor):
    if len(cursor) != 2 or not all(isinstance(value, str) for value in cursor):
        raise ValueError("Invalid scheduled crawl cursor")
    timestamp = parse_datetime(cursor[0])
    pk = compact_uuid(cursor[1])
    if timestamp is None or timezone.is_naive(timestamp):
        raise ValueError("Invalid scheduled crawl cursor")
    return Q(created_at__lt=timestamp) | Q(created_at=timestamp, pk__lt=pk)


def _selection(request, parent):
    key = "crawl" if parent or request.GET.get("crawl") else "crawl_schedule"
    if not (selected := request.GET.get(key)):
        return None
    try:
        pk = compact_uuid(selected)
    except ValueError:
        return None
    if key == "crawl" and not parent:
        return Crawl.objects.filter(pk=pk).values_list("schedule_id", flat=True).first()
    return pk


def schedule_entries_page(request, *, term, parent, cursor, limit):
    if not schedule_sidebar_allowed(request):
        return [], None
    user = request.user
    parent = parent or ""
    selected = _selection(request, parent) if not term else None
    if parent:
        parent = str(compact_uuid(parent))
        scope = "crawl"
        # The template's original crawl is part of the native schedule
        # history, just like later runs generated by the scheduler.
        rows = Crawl.objects.filter(schedule_id=parent).values("pk", "created_at")
    else:
        scope = "crawl_schedule"
        rows = CrawlSchedule.objects.annotate(
            template_label=F("template__label"),
            urls=F("template__urls"),
            url_prefix=Substr("template__urls", 1, 256),
            has_children=Exists(Crawl.objects.filter(schedule_id=OuterRef("pk"))),
        ).values("pk", "created_at", "schedule", "urls", "has_children")
        if term:
            alias = SCHEDULE_ALIASES.get(term.casefold())
            match = (
                Q(label__icontains=term) | Q(template_label__icontains=term) | Q(url_prefix__icontains=term) | Q(schedule__icontains=term)
            )
            if alias:
                match |= Q(schedule=alias)
            rows = rows.filter(match)
    if cursor is not None:
        rows = rows.filter(_cursor_filter(cursor))
        if selected:
            # The selected entry was already revealed on the first page.
            rows = rows.exclude(pk=selected)

    model_name = "crawl" if parent else "crawlschedule"
    action = "Edit" if user.has_perm(f"crawls.change_{model_name}") else "View"
    can_delete = user.has_perm(f"crawls.delete_{model_name}")
    page = list(rows.order_by("-created_at", "-pk")[: limit + 1])
    next_key = None
    if len(page) > limit:
        last = page[limit - 1]
        next_key = [last["created_at"].isoformat(), str(last["pk"])]
    page = page[:limit]
    if selected and cursor is None and all(row["pk"] != selected for row in page):
        # Keep one explicit selection reachable without loading its earlier pages.
        if selected_row := rows.filter(pk=selected).first():
            page.append(selected_row)
    entries = []
    for row in page:
        pk = str(row["pk"])
        entries.append(
            {
                "id": pk,
                "name": timezone.localtime(row["created_at"]).strftime("%Y-%m-%d %H:%M") if parent else _schedule_name(row),
                "scope": scope,
                "filter_value": pk,
                "parent_id": parent,
                "has_children": row.get("has_children", False),
                "expand": not parent and row["pk"] == selected,
                "delete_url": reverse(f"admin:crawls_{model_name}_delete", args=[pk]) if can_delete else "",
                "delete_label": "Delete Crawl" if parent else "Delete Scheduled Crawl",
                "actions": [{"label": action, "url": reverse(f"admin:crawls_{model_name}_change", args=[pk])}],
            },
        )
    return entries, next_key
